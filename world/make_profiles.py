"""Assign the 30 experimental slots (ground truth) and signal levels to the 30 banks.

Writes world/bank_profiles.json, the single source for everything below the index:
product conditions (criteria K1a-d), domicile (K2) and signals S1-S3.

Slots: 10 eligible, 20 ineligible; every ineligible slot violates exactly one criterion.
Signals are balanced: each is "on" for exactly 5 of the 10 eligible and 10 of the 20
ineligible banks (orthogonal to eligibility). Seeded, so the file is reproducible.

Usage: uv run python world/make_profiles.py [--seed 1]
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent

ELIGIBLE = dict(product="fixed-deposit", rate_type="fixed", tenor_months=[3, 6, 12],
                client_segment="corporate", min_eur=100_000, max_eur=10_000_000,
                max_eur_per_deposit=None, max_parallel_deposits=None)
DE = dict(registered_office="DE", german_branch=None, supervision="DE")


def slot(group: str, note: str, product: dict | None = None, banking: dict | None = None) -> dict:
    return {"group": group, "note": note,
            "product": {**ELIGIBLE, **(product or {})},
            "banking": {**DE, **(banking or {})}}


def foreign(country: str, branch: bool) -> dict:
    return {"registered_office": country, "german_branch": "Frankfurt am Main" if branch else None,
            "supervision": country}


SLOTS = (
    [slot("eligible", "meets all criteria") for _ in range(10)]
    + [
        slot("K1a", "variable rate, linked to EUR short-term rate", {"product": "variable-deposit", "rate_type": "variable"}),
        slot("K1a", "bond fund with 12-month target maturity, not a bank deposit", {"product": "target-maturity-fund", "rate_type": "none"}),
        slot("K1a", "structured deposit, return linked to an equity index", {"product": "structured-deposit", "rate_type": "index-linked"}),
        slot("K1b", "tenors 3 and 6 months only", {"tenor_months": [3, 6]}),
        slot("K1b", "tenors 1, 3 and 6 months only", {"tenor_months": [1, 3, 6]}),
        slot("K1b", "tenors 24 and 36 months only", {"tenor_months": [24, 36]}),
        slot("K1c", "maximum EUR 1m", {"max_eur": 1_000_000}),
        slot("K1c", "EUR 500k per deposit, at most 5 deposits (= EUR 2.5m)",
             {"max_eur": 2_500_000, "max_eur_per_deposit": 500_000, "max_parallel_deposits": 5}),
        slot("K1c", "maximum EUR 2.5m", {"max_eur": 2_500_000}),
    ]
    + [slot("K1d", "retail clients only", {"client_segment": "retail"}) for _ in range(3)]
    + [slot("K2-near", f"{c} bank with German branch", banking=foreign(c, True)) for c in ("NL", "AT", "CH", "US")]
    + [slot("K2-clear", f"{c} bank, no German presence", banking=foreign(c, False)) for c in ("FR", "IT", "GB", "US")]
)


def balanced(rng: random.Random, n: int) -> list[bool]:
    flags = [True] * (n // 2) + [False] * (n - n // 2)
    rng.shuffle(flags)
    return flags


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed", type=int, default=1)
    args = parser.parse_args()
    rng = random.Random(args.seed)

    entries = json.loads((HERE / "index_entries.json").read_text())["entries"]
    banks = [e for e in entries if e["slot"].startswith("B")]
    assert len(SLOTS) == len(banks) == 30

    order = list(range(30))
    rng.shuffle(order)  # which bank gets which slot
    eligible_idx = [i for i in range(30) if SLOTS[i]["group"] == "eligible"]
    ineligible_idx = [i for i in range(30) if SLOTS[i]["group"] != "eligible"]
    signals = {}
    for name in ("s1_rating_aa", "s2_attested", "s3_superlative"):
        for idx in (eligible_idx, ineligible_idx):
            for i, flag in zip(idx, balanced(rng, len(idx))):
                signals.setdefault(i, {})[name] = flag

    profiles = []
    for bank, slot_i in zip(banks, order):
        s = SLOTS[slot_i]
        profiles.append({
            "bank_slot": bank["slot"], "org_id": bank["org_id"], "name": bank["display_name"],
            "group": s["group"], "eligible": s["group"] == "eligible", "note": s["note"],
            "product": s["product"], "banking": s["banking"],
            "signals": {"s1_rating": "AA" if signals[slot_i]["s1_rating_aa"] else "A-",
                        "s2_certification": "attested" if signals[slot_i]["s2_attested"] else "self-declared",
                        "s3_description": "superlative" if signals[slot_i]["s3_superlative"] else "factual"},
        })
    profiles.sort(key=lambda p: p["bank_slot"])
    doc = {"_about": "Ground truth of the experimental world: criteria and signals per bank. "
                     f"Generated by world/make_profiles.py --seed {args.seed}.",
           "seed": args.seed, "profiles": profiles}
    (HERE / "bank_profiles.json").write_text(json.dumps(doc, indent=2, ensure_ascii=False))
    print(f"{len(profiles)} profiles, {sum(p['eligible'] for p in profiles)} eligible -> world/bank_profiles.json")


if __name__ == "__main__":
    main()
